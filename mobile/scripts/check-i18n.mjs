// 1) Regenerates src/i18n/resources.ts from the JSON files in src/i18n/locales.
// 2) Verifies every t('key') used in src exists in en.json, and reports coverage per locale.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'src/i18n/locales');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
const codes = files.map((f) => f.replace('.json', ''));
fs.writeFileSync(path.join(root, 'src/i18n/resources.ts'),
  `// Generated by scripts/check-i18n.mjs — do not edit.\n${codes.map((c) => `import ${c.replace(/\W/g, '_')} from './locales/${c}.json';`).join('\n')}\n\nexport const resources = {\n${codes.map((c) => `  ${JSON.stringify(c)}: { translation: ${c.replace(/\W/g, '_')} },`).join('\n')}\n};\n`);

const flat = (o, p = '') => Object.entries(o).flatMap(([k, v]) => (typeof v === 'object' ? flat(v, `${p}${k}.`) : [`${p}${k}`]));
const en = new Set(flat(JSON.parse(fs.readFileSync(path.join(dir, 'en.json'), 'utf8'))));
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : /\.tsx?$/.test(e.name) ? [path.join(d, e.name)] : []));
const missing = new Set();
for (const f of walk(path.join(root, 'src'))) {
  const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(/\bt\(\s*['"]([a-z_]+\.[A-Za-z0-9_.]+)['"]/g)) if (!en.has(m[1])) missing.add(`${m[1]}  (${path.relative(root, f)})`);
}
let bad = 0;
const flatV = (o, p = '') => Object.fromEntries(Object.entries(o).flatMap(([k, v]) => (typeof v === 'object' ? Object.entries(flatV(v, `${p}${k}.`)) : [[`${p}${k}`, v]])));
const enV = flatV(JSON.parse(fs.readFileSync(path.join(dir, 'en.json'), 'utf8')));
const vars = (s) => [...String(s).matchAll(/\{\{\w+\}\}/g)].map((m) => m[0]).sort().join();
for (const c of codes) {
  const vals = flatV(JSON.parse(fs.readFileSync(path.join(dir, `${c}.json`), 'utf8')));
  const keys = new Set(Object.keys(vals));
  const badVars = Object.keys(vals).filter((k) => k in enV && vars(vals[k]) !== vars(enV[k]));
  if (badVars.length) { console.error(`${c}: placeholder mismatch in ${badVars.join(', ')}`); bad = 1; }
  const lacking = [...en].filter((k) => !keys.has(k));
  const ph = [...en].filter((k) => keys.has(k)).length;
  console.log(`${c.padEnd(4)} ${String(ph).padStart(4)}/${en.size}${lacking.length ? `  missing ${lacking.length}` : ''}`);
}
if (missing.size) { console.error('\nKeys used in code but missing from en.json:\n' + [...missing].join('\n')); bad = 1; }
process.exit(bad);
